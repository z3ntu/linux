/**
 * s5k3p9sp_enum_frame_size() - Enumerate V4L2 sub-device frame sizes
 * @sd: pointer to s5k3p9sp V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fsize: V4L2 sub-device size enumeration need to be filled
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_enum_frame_size(struct v4l2_subdev *sd,
				  struct v4l2_subdev_state *sd_state,
				  struct v4l2_subdev_frame_size_enum *fsize)
{
	if (fsize->index > 0)
		return -EINVAL;

	if (fsize->code != supported_mode.code)
		return -EINVAL;

	fsize->min_width = supported_mode.width;
	fsize->max_width = fsize->min_width;
	fsize->min_height = supported_mode.height;
	fsize->max_height = fsize->min_height;

	return 0;
}

/**
 * s5k3p9sp_fill_pad_format() - Fill subdevice pad format
 *                            from selected sensor mode
 * @s5k3p9sp: pointer to s5k3p9sp device
 * @mode: pointer to s5k3p9sp_mode sensor mode
 * @fmt: V4L2 sub-device format need to be filled
 */
static void s5k3p9sp_fill_pad_format(struct s5k3p9sp *s5k3p9sp,
				   const struct s5k3p9sp_mode *mode,
				   struct v4l2_subdev_format *fmt)
{
	fmt->format.width = mode->width;
	fmt->format.height = mode->height;
	fmt->format.code = mode->code;
	fmt->format.field = V4L2_FIELD_NONE;
	fmt->format.colorspace = V4L2_COLORSPACE_RAW;
	fmt->format.ycbcr_enc = V4L2_YCBCR_ENC_DEFAULT;
	fmt->format.quantization = V4L2_QUANTIZATION_DEFAULT;
	fmt->format.xfer_func = V4L2_XFER_FUNC_NONE;
}

/**
 * s5k3p9sp_get_pad_format() - Get subdevice pad format
 * @sd: pointer to s5k3p9sp V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fmt: V4L2 sub-device format need to be set
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_get_pad_format(struct v4l2_subdev *sd,
				 struct v4l2_subdev_state *sd_state,
				 struct v4l2_subdev_format *fmt)
{
	struct s5k3p9sp *s5k3p9sp = to_s5k3p9sp(sd);

	mutex_lock(&s5k3p9sp->mutex);

	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
		struct v4l2_mbus_framefmt *framefmt;

		framefmt = v4l2_subdev_state_get_format(sd_state, fmt->pad);
		fmt->format = *framefmt;
	} else {
		s5k3p9sp_fill_pad_format(s5k3p9sp, s5k3p9sp->cur_mode, fmt);
	}

	mutex_unlock(&s5k3p9sp->mutex);

	return 0;
}

/**
 * s5k3p9sp_set_pad_format() - Set subdevice pad format
 * @sd: pointer to s5k3p9sp V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fmt: V4L2 sub-device format need to be set
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_set_pad_format(struct v4l2_subdev *sd,
				 struct v4l2_subdev_state *sd_state,
				 struct v4l2_subdev_format *fmt)
{
	struct s5k3p9sp *s5k3p9sp = to_s5k3p9sp(sd);
	const struct s5k3p9sp_mode *mode;
	int ret = 0;

	mutex_lock(&s5k3p9sp->mutex);

	mode = &supported_mode;
	s5k3p9sp_fill_pad_format(s5k3p9sp, mode, fmt);

	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
		struct v4l2_mbus_framefmt *framefmt;

		framefmt = v4l2_subdev_state_get_format(sd_state, fmt->pad);
		*framefmt = fmt->format;
	} else {
		ret = s5k3p9sp_update_controls(s5k3p9sp, mode);
		if (!ret)
			s5k3p9sp->cur_mode = mode;
	}

	mutex_unlock(&s5k3p9sp->mutex);

	return ret;
}

/**
 * s5k3p9sp_init_state() - Initialize sub-device state
 * @sd: pointer to s5k3p9sp V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_init_state(struct v4l2_subdev *sd,
			     struct v4l2_subdev_state *sd_state)
{
	struct s5k3p9sp *s5k3p9sp = to_s5k3p9sp(sd);
	struct v4l2_subdev_format fmt = { 0 };

	fmt.which = sd_state ? V4L2_SUBDEV_FORMAT_TRY : V4L2_SUBDEV_FORMAT_ACTIVE;
	s5k3p9sp_fill_pad_format(s5k3p9sp, &supported_mode, &fmt);

	return s5k3p9sp_set_pad_format(sd, sd_state, &fmt);
}

/**
 * s5k3p9sp_start_streaming() - Start sensor stream
 * @s5k3p9sp: pointer to s5k3p9sp device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_start_streaming(struct s5k3p9sp *s5k3p9sp)
{
	const struct s5k3p9sp_reg_list *reg_list;
	int ret;

	/* Write sensor mode registers */
	reg_list = &s5k3p9sp->cur_mode->reg_list;
	ret = cci_multi_reg_write(s5k3p9sp->regmap, reg_list->regs,
				  reg_list->num_of_regs, NULL);
	if (ret) {
		dev_err(s5k3p9sp->dev, "fail to write initial registers\n");
		return ret;
	}

	/* Setup handler will write actual exposure and gain */
	ret =  __v4l2_ctrl_handler_setup(s5k3p9sp->sd.ctrl_handler);
	if (ret) {
		dev_err(s5k3p9sp->dev, "fail to setup handler\n");
		return ret;
	}

	/* Delay is required before streaming*/
	usleep_range(7400, 8000);

	/* Start streaming */
	cci_write(s5k3p9sp->regmap, S5K3P9SP_REG_MODE_SELECT, S5K3P9SP_MODE_STREAMING, &ret);
	if (ret) {
		dev_err(s5k3p9sp->dev, "fail to start streaming\n");
		return ret;
	}

	return 0;
}

/**
 * s5k3p9sp_stop_streaming() - Stop sensor stream
 * @s5k3p9sp: pointer to s5k3p9sp device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_stop_streaming(struct s5k3p9sp *s5k3p9sp)
{
	return cci_write(s5k3p9sp->regmap, S5K3P9SP_REG_MODE_SELECT,
			 S5K3P9SP_MODE_STANDBY, NULL);
}

/**
 * s5k3p9sp_set_stream() - Enable sensor streaming
 * @sd: pointer to s5k3p9sp subdevice
 * @enable: set to enable sensor streaming
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_set_stream(struct v4l2_subdev *sd, int enable)
{
	struct s5k3p9sp *s5k3p9sp = to_s5k3p9sp(sd);
	int ret;

	mutex_lock(&s5k3p9sp->mutex);

	if (enable) {
		ret = pm_runtime_resume_and_get(s5k3p9sp->dev);
		if (ret)
			goto error_unlock;

		ret = s5k3p9sp_start_streaming(s5k3p9sp);
		if (ret)
			goto error_power_off;
	} else {
		s5k3p9sp_stop_streaming(s5k3p9sp);
		pm_runtime_put(s5k3p9sp->dev);
	}

	mutex_unlock(&s5k3p9sp->mutex);

	return 0;

error_power_off:
	pm_runtime_put(s5k3p9sp->dev);
error_unlock:
	mutex_unlock(&s5k3p9sp->mutex);

	return ret;
}

/**
 * s5k3p9sp_detect() - Detect s5k3p9sp sensor
 * @s5k3p9sp: pointer to s5k3p9sp device
 *
 * Return: 0 if successful, -EIO if sensor id does not match
 */
static int s5k3p9sp_detect(struct s5k3p9sp *s5k3p9sp)
{
	int ret;
	u64 val;

	ret = cci_read(s5k3p9sp->regmap, S5K3P9SP_REG_CHIP_ID, &val, NULL);
	if (ret)
		return ret;

	if (val != S5K3P9SP_CHIP_ID) {
		dev_err(s5k3p9sp->dev, "chip id mismatch: %x!=%llx\n",
			S5K3P9SP_CHIP_ID, val);
		return -ENXIO;
	}

	return 0;
}

/**
 * s5k3p9sp_parse_hw_config() - Parse HW configuration and check if supported
 * @s5k3p9sp: pointer to s5k3p9sp device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int s5k3p9sp_parse_hw_config(struct s5k3p9sp *s5k3p9sp)
{
	struct fwnode_handle *fwnode = dev_fwnode(s5k3p9sp->dev);
	struct v4l2_fwnode_endpoint bus_cfg = {};
	struct fwnode_handle *ep;
	unsigned long rate;
	unsigned int i;
	int ret;

	if (!fwnode)
		return -ENXIO;

	/* Request optional reset pin */
	s5k3p9sp->reset_gpio = devm_gpiod_get_optional(s5k3p9sp->dev, "reset",
						     GPIOD_OUT_LOW);
	if (IS_ERR(s5k3p9sp->reset_gpio)) {
		dev_err(s5k3p9sp->dev, "failed to get reset gpio %ld\n",
			PTR_ERR(s5k3p9sp->reset_gpio));
		return PTR_ERR(s5k3p9sp->reset_gpio);
	}

	/* Get sensor input clock */
	s5k3p9sp->inclk = devm_clk_get(s5k3p9sp->dev, NULL);
	if (IS_ERR(s5k3p9sp->inclk)) {
		dev_err(s5k3p9sp->dev, "could not get inclk\n");
		return PTR_ERR(s5k3p9sp->inclk);
	}

	rate = clk_get_rate(s5k3p9sp->inclk);
	if (rate != S5K3P9SP_INCLK_RATE) {
		dev_err(s5k3p9sp->dev, "inclk frequency mismatch\n");
		return -EINVAL;
	}

	/* Get optional DT defined regulators */
	for (i = 0; i < ARRAY_SIZE(s5k3p9sp_supply_names); i++)
		s5k3p9sp->supplies[i].supply = s5k3p9sp_supply_names[i];

	ret = devm_regulator_bulk_get(s5k3p9sp->dev,
				      ARRAY_SIZE(s5k3p9sp_supply_names),
				      s5k3p9sp->supplies);
	if (ret)
		return ret;

	ep = fwnode_graph_get_next_endpoint(fwnode, NULL);
	if (!ep)
		return -ENXIO;

	ret = v4l2_fwnode_endpoint_alloc_parse(ep, &bus_cfg);
	fwnode_handle_put(ep);
	if (ret)
		return ret;

	if (bus_cfg.bus_type != V4L2_MBUS_CSI2_DPHY) {
		dev_err(s5k3p9sp->dev, "selected bus-type is not supported\n");
		ret = -EINVAL;
		goto done_endpoint_free;
	}

	if (bus_cfg.bus.mipi_csi2.num_data_lanes != S5K3P9SP_NUM_DATA_LANES) {
		dev_err(s5k3p9sp->dev,
			"number of CSI2 data lanes %d is not supported\n",
			bus_cfg.bus.mipi_csi2.num_data_lanes);
		ret = -EINVAL;
		goto done_endpoint_free;
	}

	if (!bus_cfg.nr_of_link_frequencies) {
		dev_err(s5k3p9sp->dev, "no link frequencies defined\n");
		ret = -EINVAL;
		goto done_endpoint_free;
	}

	for (i = 0; i < bus_cfg.nr_of_link_frequencies; i++)
		if (bus_cfg.link_frequencies[i] == S5K3P9SP_LINK_FREQ)
			goto done_endpoint_free;

	ret = -EINVAL;

done_endpoint_free:
	v4l2_fwnode_endpoint_free(&bus_cfg);

	return ret;
}

