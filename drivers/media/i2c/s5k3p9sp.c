/* Chip ID */
#define S5K3P9SP_REG_CHIP_ID		CCI_REG16(0x0000)
#define S5K3P9SP_CHIP_ID			0x3109

/* Streaming Mode */
#define S5K3P9SP_REG_MODE_SELECT		CCI_REG8(0x0100)
#define S5K3P9SP_MODE_STANDBY		0x00
#define S5K3P9SP_MODE_STREAMING		0x01

/* Lines per frame */
#define S5K3P9SP_REG_LPFR			CCI_REG16(0x0340)

/* Exposure control */
#define S5K3P9SP_REG_EXPOSURE		CCI_REG16(0x0202)
#define S5K3P9SP_EXPOSURE_MIN		8
#define S5K3P9SP_EXPOSURE_OFFSET		22
#define S5K3P9SP_EXPOSURE_STEP		1
#define S5K3P9SP_EXPOSURE_DEFAULT		0x0648

/* Analog gain control */
#define S5K3P9SP_REG_ANALOG_GAIN		CCI_REG16(0x0204)
#define S5K3P9SP_ANA_GAIN_MIN		0
#define S5K3P9SP_ANA_GAIN_MAX		978
#define S5K3P9SP_ANA_GAIN_STEP		1
#define S5K3P9SP_ANA_GAIN_DEFAULT		0

/* Group hold register */
#define S5K3P9SP_REG_HOLD		CCI_REG8(0x0104)

/* Input clock rate */
#define S5K3P9SP_INCLK_RATE	24000000

/* CSI2 HW configuration */
#define S5K3P9SP_LINK_FREQ	600000000
#define S5K3P9SP_NUM_DATA_LANES	4

#define S5K3P9SP_REG_MIN		0x00
#define S5K3P9SP_REG_MAX		0xffff

/**
 * struct s5k3p9sp_reg_list - s5k3p9sp sensor register list
 * @num_of_regs: Number of registers in the list
 * @regs: Pointer to register list
 */
struct s5k3p9sp_reg_list {
	u32 num_of_regs;
	const struct cci_reg_sequence *regs;
};

/**
 * struct s5k3p9sp_mode - s5k3p9sp sensor mode structure
 * @width: Frame width
 * @height: Frame height
 * @code: Format code
 * @hblank: Horizontal blanking in lines
 * @vblank: Vertical blanking in lines
 * @vblank_min: Minimum vertical blanking in lines
 * @vblank_max: Maximum vertical blanking in lines
 * @pclk: Sensor pixel clock
 * @link_freq_idx: Link frequency index
 * @reg_list: Register list for sensor mode
 */
struct s5k3p9sp_mode {
	u32 width;
	u32 height;
	u32 code;
	u32 hblank;
	u32 vblank;
	u32 vblank_min;
	u32 vblank_max;
	u64 pclk;
	u32 link_freq_idx;
	struct s5k3p9sp_reg_list reg_list;
};

static const char * const s5k3p9sp_supply_names[] = {
	"vdda",		/* 2.8V Analog Power */
	"vddio",	/* 1.8V Interface Power */
	"vddd",		/* 1.2V Digital Power */
};

/**
 * struct s5k3p9sp - s5k3p9sp sensor device structure
 * @dev: Pointer to generic device
 * @client: Pointer to i2c client
 * @sd: V4L2 sub-device
 * @pad: Media pad. Only one pad supported
 * @reset_gpio: Sensor reset gpio
 * @inclk: Sensor input clock
 * @supplies: Regulator supplies
 * @ctrl_handler: V4L2 control handler
 * @link_freq_ctrl: Pointer to link frequency control
 * @pclk_ctrl: Pointer to pixel clock control
 * @hblank_ctrl: Pointer to horizontal blanking control
 * @vblank_ctrl: Pointer to vertical blanking control
 * @exp_ctrl: Pointer to exposure control
 * @again_ctrl: Pointer to analog gain control
 * @vblank: Vertical blanking in lines
 * @cur_mode: Pointer to current selected sensor mode
 * @mutex: Mutex for serializing sensor controls
 */
struct s5k3p9sp {
	struct device *dev;
	struct i2c_client *client;
	struct v4l2_subdev sd;
	struct media_pad pad;
	struct gpio_desc *reset_gpio;
	struct clk *inclk;
	struct regulator_bulk_data supplies[ARRAY_SIZE(s5k3p9sp_supply_names)];
	struct v4l2_ctrl_handler ctrl_handler;
	struct v4l2_ctrl *link_freq_ctrl;
	struct v4l2_ctrl *pclk_ctrl;
	struct v4l2_ctrl *hblank_ctrl;
	struct v4l2_ctrl *vblank_ctrl;
	struct {
		struct v4l2_ctrl *exp_ctrl;
		struct v4l2_ctrl *again_ctrl;
	};
	u32 vblank;
	const struct s5k3p9sp_mode *cur_mode;
	struct mutex mutex;
	struct regmap *regmap;
};

